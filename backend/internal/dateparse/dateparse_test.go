package dateparse

import (
	"testing"
	"time"
)

func TestParse(t *testing.T) {
	loc := time.FixedZone("MSK", 3*3600)
	now := time.Date(2026, 11, 10, 15, 0, 0, 0, loc) // вторник
	cases := []struct{ in, from, to string }{
		{"хочу отгул завтра", "2026-11-11", "2026-11-11"},
		{"послезавтра можно?", "2026-11-12", "2026-11-12"},
		{"сегодня", "2026-11-10", "2026-11-10"},
		{"отгул в пятницу", "2026-11-13", "2026-11-13"},
		{"в следующую пятницу", "2026-11-20", "2026-11-20"},
		{"в следующий понедельник", "2026-11-16", "2026-11-16"},
		{"в среду", "2026-11-11", "2026-11-11"},
		{"во вторник", "2026-11-17", "2026-11-17"},
		{"с понедельника по среду", "2026-11-16", "2026-11-18"},
		{"13 ноября", "2026-11-13", "2026-11-13"},
		{"с 16 по 18 ноября", "2026-11-16", "2026-11-18"},
		{"16-18 ноября", "2026-11-16", "2026-11-18"},
		{"5 мая", "2027-05-05", "2027-05-05"},
		{"1 ноября", "2027-11-01", "2027-11-01"},
		{"13.11", "2026-11-13", "2026-11-13"},
		{"13.11.26", "2026-11-13", "2026-11-13"},
		{"2026-12-01", "2026-12-01", "2026-12-01"},
		{"в пятницу на 2 дня", "2026-11-13", "2026-11-16"},
		{"с 16 ноября на три дня", "2026-11-16", "2026-11-18"},
		{"в субботу и воскресенье", "2026-11-14", "2026-11-15"},
	}
	for _, c := range cases {
		r, ok := Parse(c.in, now)
		if !ok || r.From.Format("2006-01-02") != c.from || r.To.Format("2006-01-02") != c.to {
			t.Errorf("%q: got %v..%v ok=%v, want %s..%s", c.in, r.From.Format("2006-01-02"), r.To.Format("2006-01-02"), ok, c.from, c.to)
		}
	}
	for _, bad := range []string{"как оформить отгул", "31.02", "32 ноября", "2026-13-01"} {
		if _, ok := Parse(bad, now); ok {
			t.Errorf("%q must not parse", bad)
		}
	}
	if d, ok := date(now, 0, 0, 1); ok || !d.IsZero() {
		t.Fatal("bad month")
	}
	if r, _ := Parse("с 18 по 16 ноября", now); !r.From.Equal(r.To) {
		t.Fatal("reverse range ignored")
	}
}
